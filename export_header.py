"""
export_header.py - turn fan_baseline.npz into baseline.h for the ESP32.

Usage (from Project/data):
    python export_header.py
    python export_header.py --out ../firmware/fan_monitor/baseline.h

Copy the generated baseline.h next to fan_monitor.ino before flashing.
"""

import argparse
import datetime
import os

import numpy as np


def fmt_array(name, arr, per_line=6):
    flat = np.asarray(arr, dtype=np.float32).ravel()
    lines = [f"const float {name}[{flat.size}] PROGMEM = {{"]
    for i in range(0, flat.size, per_line):
        chunk = ", ".join(f"{v:.8e}f" for v in flat[i:i + per_line])
        lines.append("    " + chunk + ("," if i + per_line < flat.size else ""))
    lines.append("};")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description="Export trained detectors to a C header")
    ap.add_argument("--baseline", default="fan_baseline.npz")
    ap.add_argument("--out", default="baseline.h")
    ap.add_argument("--data-dir", default=".")
    args = ap.parse_args()

    path = os.path.join(args.data_dir, args.baseline)
    if not os.path.exists(path):
        raise SystemExit(f"{args.baseline} not found - run fan_train.py first")
    bl = np.load(path, allow_pickle=True)

    n_feat = int(bl["n_feat"])
    latent = int(bl["latent"])
    window = int(bl["window"])
    hop = int(bl["hop"])
    fs = float(bl["fs"])
    maha_thr = float(bl["maha_thr"])
    ae_thr = float(bl["ae_thr"])

    bytes_total = (n_feat * 2 + n_feat * n_feat + n_feat * latent * 2 + latent + n_feat) * 4

    parts = [
        "// baseline.h - generated by export_header.py, do not edit by hand",
        f"// generated {datetime.datetime.now().isoformat(timespec='seconds')}",
        f"// trained on: {', '.join(str(f) for f in bl['healthy_files'])}",
        f"// footprint: {bytes_total} bytes of float constants",
        "",
        "#ifndef BASELINE_H",
        "#define BASELINE_H",
        "",
        "#include <pgmspace.h>",
        "",
        f"#define BASE_FS          {fs:.1f}f",
        f"#define BASE_WINDOW      {window}",
        f"#define BASE_HOP         {hop}",
        f"#define BASE_N_FEAT      {n_feat}",
        f"#define BASE_LATENT      {latent}",
        f"#define BASE_MAHA_THR    {maha_thr:.8g}f",
        f"#define BASE_AE_THR      {ae_thr:.8g}f",
        "",
        "// feature standardization: z = (x - mu) / sigma",
        fmt_array("BASE_MU", bl["mu"]),
        "",
        fmt_array("BASE_SIGMA", bl["sigma"]),
        "",
        "// Mahalanobis: d^2 = || A z ||^2, A row-major [N_FEAT][N_FEAT]",
        fmt_array("BASE_A", bl["A"]),
        "",
        "// autoencoder: h = tanh(z W1 + b1); zr = h W2 + b2; score = mean((zr - z)^2)",
        fmt_array("BASE_W1", bl["W1"]),
        "",
        fmt_array("BASE_B1", bl["b1"]),
        "",
        fmt_array("BASE_W2", bl["W2"]),
        "",
        fmt_array("BASE_B2", bl["b2"]),
        "",
        "#endif  // BASELINE_H",
        "",
    ]

    out_path = os.path.join(args.data_dir, args.out) if not os.path.isabs(args.out) else args.out
    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    with open(out_path, "w") as fh:
        fh.write("\n".join(parts))

    print(f"Wrote {out_path}")
    print(f"  features      {n_feat}")
    print(f"  latent units  {latent}")
    print(f"  maha thr      {maha_thr:.4f}")
    print(f"  AE thr        {ae_thr:.6f}")
    print(f"  constants     {bytes_total} bytes")
    print("\nCopy this file into the fan_monitor sketch folder, then flash fan_monitor.ino")


if __name__ == "__main__":
    main()